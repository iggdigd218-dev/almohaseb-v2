// (2026-09-24) نبضة تغيّر البيانات من خارج شجرة الواجهة.
//
// المشكلة: الزر العائم (البيع السريع) يكتب في قاعدة البيانات من خدمة تعمل
// خارج شاشة نقطة البيع، فلا أحد يخبر الواجهة أن الأرصدة تغيّرت ⇒ تبقى
// الكميات المعروضة قديمة حتى إعادة فتح التطبيق. Riverpod يحتاج `WidgetRef`
// وليس متاحاً في الخدمة، لذا: نبضة عالمية واحدة تنقلها الخدمة، وكل شاشة
// معنية (نقطة البيع/المخزون) تستمع إليها وتحدّث مزوّداتها.
import 'package:flutter/foundation.dart';

/// عدّاد متزايد: كل كتابة خارجية على البيانات تزيده بمقدار واحد.
final ValueNotifier<int> dataChangeTick = ValueNotifier<int>(0);

/// يعلن أن البيانات تغيّرت من خارج الواجهة (خدمة، زر عائم، استيراد…).
void markDataChanged() => dataChangeTick.value++;
